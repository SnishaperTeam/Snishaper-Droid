// The evolution tester itself does not need a local CA: it talks to upstream
// servers directly. Only the *generated rule* needs to be filtered: rules from
// domain_fronting / ech / quic need MITM or QUIC local TLS termination and are
// rejected; tls_fragment / direct results are applicable.

// StartEvolutionTest starts an asynchronous domain evolution run.
func (a *App) StartEvolutionTest(domainsJSON string, enableIPv6 bool) (err error) {
	defer recoverError(&err)

	var domains []string
	if err := json.Unmarshal([]byte(domainsJSON), &domains); err != nil {
		return fmt.Errorf("parse domains: %w", err)
	}
	clean := make([]string, 0, len(domains))
	seen := make(map[string]struct{}, len(domains))
	for _, domain := range domains {
		domain = strings.TrimSpace(strings.ToLower(domain))
		if domain == "" {
			continue
		}
		if _, ok := seen[domain]; ok {
			continue
		}
		seen[domain] = struct{}{}
		clean = append(clean, domain)
		if len(clean) >= 200 {
			break
		}
	}
	if len(clean) == 0 {
		return fmt.Errorf("domain list is empty")
	}

	a.opMu.Lock()
	defer a.opMu.Unlock()
	rm, srv, err := a.engineLocked()
	if err != nil {
		return err
	}

	a.mu.Lock()
	router := a.evoAutoRouter
	oldPoll := a.evoPollStop
	poll := make(chan struct{})
	a.evoPollStop = poll
	a.mu.Unlock()
	if router == nil {
		close(poll)
		return fmt.Errorf("engine is not started")
	}
	if oldPoll != nil {
		close(oldPoll)
	}

	tester := evolution.NewTester(rm, srv, srv.GetDoHResolver(), router, a.appendLog)
	cfg := evolution.DefaultTestConfig()
	cfg.EnableIPv6 = enableIPv6
	task, err := tester.StartTest(clean, cfg)
	if err != nil {
		a.mu.Lock()
		if a.evoPollStop == poll {
			a.evoPollStop = nil
		}
		a.mu.Unlock()
		close(poll)
		return fmt.Errorf("start evolution test: %w", err)
	}

	a.mu.Lock()
	a.tester = tester
	a.evoRunning = true
	a.mu.Unlock()

	a.dispatchLog(fmt.Sprintf("[evolution] started for %d domain(s)", len(clean)))
	if task != nil {
		a.pushEvolution(marshalJSON(task))
	}
	go a.pollEvolution(poll, tester)
	return nil
}

// pollEvolution pushes progress snapshots every 500 ms until the task ends.
func (a *App) pollEvolution(stop <-chan struct{}, tester *evolution.Tester) {
	ticker := time.NewTicker(500 * time.Millisecond)
	defer ticker.Stop()
	for {
		select {
		case <-stop:
			a.mu.Lock()
			a.evoRunning = false
			a.mu.Unlock()
			return
		case <-ticker.C:
			task := tester.Snapshot()
			if task == nil {
				continue
			}
			a.pushEvolution(marshalJSON(task))
			if task.Status != evolution.StatusRunning && task.Status != evolution.StatusPending {
				a.mu.Lock()
				a.evoRunning = false
				a.mu.Unlock()
				a.dispatchLog("[evolution] task finished: " + string(task.Status))
				return
			}
		}
	}
}

// StopEvolutionTest stops the running evolution task (if any).
func (a *App) StopEvolutionTest() (err error) {
	defer recoverError(&err)
	a.mu.Lock()
	tester := a.tester
	poll := a.evoPollStop
	a.evoPollStop = nil
	a.evoRunning = false
	a.mu.Unlock()
	if poll != nil {
		close(poll)
	}
	if tester == nil {
		return nil
	}
	tester.StopTest()
	a.dispatchLog("[evolution] stopped by user")
	return nil
}

// GetEvolutionStatusJSON returns the current evolution.TestTask snapshot.
func (a *App) GetEvolutionStatusJSON() (out string) {
	defer recoverString(&out)
	a.mu.Lock()
	tester := a.tester
	last := a.lastTaskJSON
	a.mu.Unlock()
	if tester == nil {
		if last != "" {
			return last
		}
		return "{}"
	}
	task := tester.Snapshot()
	if task == nil {
		if last != "" {
			return last
		}
		return "{}"
	}
	return marshalJSON(task)
}

// ApplyEvolutionRule applies one generated rule to the site group list. Only
// tls_fragment / direct results may be applied; the rest need a local CA.
func (a *App) ApplyEvolutionRule(ruleID string) (err error) {
	defer recoverError(&err)

	a.opMu.Lock()
	defer a.opMu.Unlock()

	rm, _, err := a.engineLocked()
	if err != nil {
		return err
	}
	a.mu.Lock()
	tester := a.tester
	a.mu.Unlock()
	if tester == nil {
		return fmt.Errorf("no evolution task is available")
	}
	rule := tester.GetTempRule(strings.TrimSpace(ruleID))
	if rule == nil {
		return fmt.Errorf("evolution rule %s not found", ruleID)
	}
	if rule.Method != evolution.MethodTLSFragment && rule.Method != evolution.MethodDirect {
		return fmt.Errorf("Android does not support rules generated by %q: only tls_fragment and direct results can be applied (this method requires a local CA)", string(rule.Method))
	}

	group := proxy.SiteGroup{}
	data, marshalErr := json.Marshal(rule.ToSiteGroup())
	if marshalErr != nil {
		return fmt.Errorf("build rule: %w", marshalErr)
	}
	if unmarshalErr := json.Unmarshal(data, &group); unmarshalErr != nil {
		return fmt.Errorf("build rule: %w", unmarshalErr)
	}
	if strings.TrimSpace(group.Name) == "" {
		group.Name = rule.Domain
	}
	group.ID = ""
	if err := sanitizeSiteGroupForWrite(&group); err != nil {
		return err
	}
	if err := rm.AddSiteGroup(group); err != nil {
		return err
	}
	tester.MarkRuleApplied(rule.ID)
	a.afterConfigChangedLocked()
	a.dispatchLog("[evolution] applied tls_fragment rule for " + rule.Domain)
	return nil
}
