#Requires -Version 7.0
<#
.SYNOPSIS
    Creates the release keystore used to sign Snishaper-Droid APK / AAB builds.

.DESCRIPTION
    Generates <repo>/keystore/release.jks (PKCS12) plus <repo>/keystore.properties,
    both of which are git-ignored. Gradle reads keystore.properties automatically
    (app/build.gradle.kts), so a plain `./gradlew :app:assembleRelease` produces a
    signed APK once this script has run.

    The password is stored in keystore.properties only; keep an offline copy of
    both files — losing them means future releases can no longer update an
    installed app (Android refuses APKs signed by a different key).

.PARAMETER Alias
    Key alias inside the keystore. Defaults to `snishaper`.

.PARAMETER Password
    Store/key password. When omitted a 24 character random password is generated.

.PARAMETER ValidYears
    Certificate validity in years. Defaults to 30 (Play requires >= 25).

.PARAMETER DistinguishedName
    X.500 name for the certificate subject.

.PARAMETER Force
    Overwrite an existing keystore and keystore.properties.

.EXAMPLE
    pwsh -File scripts/init-keystore.ps1
#>
[CmdletBinding()]
param(
    [string]$Alias = "snishaper",
    [string]$Password = "",
    [int]$ValidYears = 30,
    [string]$DistinguishedName = "CN=Snishaper-Droid, OU=SniShaper Team, O=SniShaperTeam, L=Unknown, ST=Unknown, C=CN",
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
$keystoreDir = Join-Path $repoRoot "keystore"
$keystorePath = Join-Path $keystoreDir "release.jks"
$propertiesPath = Join-Path $repoRoot "keystore.properties"

if ((Test-Path $keystorePath) -and -not $Force) {
    throw "keystore already exists: $keystorePath (use -Force to replace it)"
}

$javaHome = $env:JAVA_HOME
if (-not $javaHome) { $javaHome = "D:\Jetbrains IDES\Android Studio\jbr" }
$keytool = Join-Path $javaHome "bin/keytool.exe"
if (-not (Test-Path $keytool)) {
    $keytool = (Get-Command keytool -ErrorAction SilentlyContinue)?.Source
}
if (-not $keytool -or -not (Test-Path $keytool)) {
    throw "keytool not found; set JAVA_HOME to a JDK (Android Studio jbr works)"
}

if (-not $Password) {
    $alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"
    $bytes = [byte[]]::new(24)
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    $Password = -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })
}

if (-not (Test-Path $keystoreDir)) {
    New-Item -ItemType Directory -Force -Path $keystoreDir | Out-Null
}
if (Test-Path $keystorePath) {
    Remove-Item -LiteralPath $keystorePath -Force
}

& $keytool -genkeypair `
    -keystore $keystorePath `
    -storetype PKCS12 `
    -alias $Alias `
    -keyalg RSA `
    -keysize 4096 `
    -validity ($ValidYears * 365) `
    -storepass $Password `
    -keypass $Password `
    -dname $DistinguishedName `
    -noprompt
if ($LASTEXITCODE -ne 0) {
    throw "keytool -genkeypair failed with exit code $LASTEXITCODE"
}

@(
    "# Generated by scripts/init-keystore.ps1 - do NOT commit.",
    "storeFile=keystore/release.jks",
    "storePassword=$Password",
    "keyAlias=$Alias",
    "keyPassword=$Password"
) | Set-Content -LiteralPath $propertiesPath -Encoding utf8

Write-Host ""
& $keytool -list -v -keystore $keystorePath -storepass $Password -alias $Alias |
    Select-String -Pattern "Alias name|Owner|Valid from|SHA256:|Signature algorithm"

Write-Host ""
Write-Host "[init-keystore] keystore   : $keystorePath"
Write-Host "[init-keystore] properties : $propertiesPath"
Write-Host "[init-keystore] alias      : $Alias"
Write-Host "[init-keystore] password   : $Password"
Write-Host "[init-keystore] Store both files offline; CI secrets:"
Write-Host "                  ANDROID_KEYSTORE_BASE64 = base64($keystorePath)"
Write-Host "                  ANDROID_KEYSTORE_PASSWORD / ANDROID_KEY_ALIAS / ANDROID_KEY_PASSWORD"
